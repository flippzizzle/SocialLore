    fun findTheme(themeId: String?, customThemes: List<CustomThemeEntity> = emptyList()): LoreThemeSpec {
        if (themeId.isNullOrBlank()) return premadeThemes.first()
        if (themeId.startsWith("custom_")) {
            val rawId = themeId.removePrefix("custom_")
            val found = customThemes.firstOrNull { it.id == rawId }
            if (found != null) return found.toLoreThemeSpec()
        }
        return premadeThemes.firstOrNull { it.id == themeId } ?: premadeThemes.first()
    }
