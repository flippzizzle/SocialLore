data class LoreThemeSpec(
    val id: String,
    val name: String,
    val category: String,
    val isDark: Boolean,
    val background: Color,
    val gradientStart: Color,
    val gradientEnd: Color,
    val cardColor: Color,
    val cardVariantColor: Color,
    val textPrimary: Color,
    val textSecondary: Color,
    val accent: Color,
    val secondaryAccent: Color,
    val borderColor: Color,
    val borderWidthDp: Float = 1.2f,
    val cardOpacity: Float = 0.92f,
    val navBarColor: Color = cardColor,
    val defaultHeadingFont: String = "Playfair Display",
    val defaultBodyFont: String = "Plus Jakarta Sans",
    val bgImageUrl: String? = null
)

fun parseHexColor(hex: String?, fallback: Color): Color {
    if (hex.isNullOrBlank()) return fallback
    return try {
        val clean = hex.trim().removePrefix("#")
        val value = clean.toLong(16)
        when (clean.length) {
            6 -> Color(0xFF000000L or value)
            8 -> Color(value)
            else -> fallback
        }
    } catch (_: Exception) {
        fallback
    }
}

fun Color.toHexString(): String {
    val a = ((alpha * 255).toInt().coerceIn(0, 255))
    val r = ((red * 255).toInt().coerceIn(0, 255))
    val g = ((green * 255).toInt().coerceIn(0, 255))
    val b = ((blue * 255).toInt().coerceIn(0, 255))
    return if (a == 255) {
        String.format("#%02X%02X%02X", r, g, b)
    } else {
        String.format("#%02X%02X%02X%02X", a, r, g, b)
    }
}

fun CustomThemeEntity.toLoreThemeSpec(): LoreThemeSpec {
    val bg = parseHexColor(bgColorHex, Color(0xFF0E0C1A))
    val card = parseHexColor(cardColorHex, Color(0xFF1D1836))
    val text = parseHexColor(textColorHex, Color(0xFFF4F1FF))
    val accent = parseHexColor(accentColorHex, Color(0xFFA855F7))
    return LoreThemeSpec(
        id = "custom_$id",
        name = name,
        category = "Custom",
        isDark = darkTheme,
        background = bg,
        gradientStart = parseHexColor(gradientStartHex, bg),
        gradientEnd = parseHexColor(gradientEndHex, bg),
        cardColor = card,
        cardVariantColor = card.copy(alpha = 0.78f),
        textPrimary = text,
        textSecondary = text.copy(alpha = 0.74f),
        accent = accent,
        secondaryAccent = accent.copy(alpha = 0.8f),
        borderColor = parseHexColor(borderColorHex, accent.copy(alpha = 0.5f)),
        borderWidthDp = borderWidthDp.toFloat().coerceIn(0f, 12f),
        cardOpacity = cardOpacity.toFloat().coerceIn(0.25f, 1f),
        navBarColor = card,
        defaultHeadingFont = headingFont,
        defaultBodyFont = bodyFont,
        bgImageUrl = bgImageUrl
    )
}

